CREATE INDEX idx_users_department        ON users(department_id);
CREATE INDEX idx_users_manager           ON users(manager_id);
CREATE INDEX idx_requisitions_requester  ON purchase_requisitions(requester_id);
CREATE INDEX idx_requisitions_department ON purchase_requisitions(department_id);
CREATE INDEX idx_requisitions_status     ON purchase_requisitions(status);
CREATE INDEX idx_req_items_requisition   ON requisition_items(requisition_id);
CREATE INDEX idx_req_items_category      ON requisition_items(category_id);
CREATE INDEX idx_approvals_requisition   ON approvals(requisition_id);
CREATE INDEX idx_approvals_decided_by    ON approvals(decided_by);
CREATE INDEX idx_po_requisition          ON purchase_orders(requisition_id);
CREATE INDEX idx_po_supplier             ON purchase_orders(supplier_id);
CREATE INDEX idx_po_status               ON purchase_orders(status);
CREATE INDEX idx_po_items_order          ON po_items(purchase_order_id);
CREATE INDEX idx_audit_entity            ON audit_logs(entity_type, entity_id);
CREATE INDEX idx_audit_performed_by      ON audit_logs(performed_by);
CREATE INDEX idx_audit_created_at        ON audit_logs(created_at);
