-- =====================================================================
-- 1. IDENTITY AND ORGANISATION
-- =====================================================================

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE departments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(20)   NOT NULL UNIQUE,
    name           VARCHAR(100)  NOT NULL UNIQUE,
    head_user_id   BIGINT,                              -- FK added after users exists
    annual_budget  NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (annual_budget >= 0),
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code  VARCHAR(30)  NOT NULL UNIQUE,
    full_name      VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,               -- BCrypt hash, never plain text
    role_id        BIGINT       NOT NULL REFERENCES roles(id),
    department_id  BIGINT       NOT NULL REFERENCES departments(id),
    manager_id     BIGINT       REFERENCES users(id),   -- reporting line (self reference)
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- departments <-> users reference each other, so this FK is added afterwards
ALTER TABLE departments
    ADD CONSTRAINT fk_departments_head_user
    FOREIGN KEY (head_user_id) REFERENCES users(id);

-- =====================================================================
-- 2. MASTER DATA
-- =====================================================================

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE suppliers (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_code       VARCHAR(30)  NOT NULL UNIQUE,
    name                VARCHAR(200) NOT NULL,
    contact_person      VARCHAR(150),
    email               VARCHAR(150),
    phone               VARCHAR(30),
    address             TEXT,
    tax_id              VARCHAR(50)  NOT NULL UNIQUE,   -- e.g. GSTIN / PAN
    status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','ACTIVE','SUSPENDED','BLACKLISTED')),
    compliance_status   VARCHAR(20)  NOT NULL DEFAULT 'UNDER_REVIEW'
        CHECK (compliance_status IN ('COMPLIANT','UNDER_REVIEW','NON_COMPLIANT')),
    performance_rating  NUMERIC(3,2) CHECK (performance_rating BETWEEN 0 AND 5),
    is_active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- many-to-many: which categories a supplier can supply
CREATE TABLE supplier_categories (
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id)  ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
    PRIMARY KEY (supplier_id, category_id)
);

-- =====================================================================
-- 3. WORKFLOW CONFIGURATION
-- A workflow applies when: min_amount <= total_amount < max_amount
-- (max_amount NULL means no upper limit)
-- =====================================================================

CREATE TABLE approval_workflows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL UNIQUE,
    min_amount  NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (min_amount >= 0),
    max_amount  NUMERIC(15,2),
    is_active   BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_workflow_amount_range
        CHECK (max_amount IS NULL OR max_amount > min_amount)
);

CREATE TABLE approval_workflow_steps (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id      BIGINT  NOT NULL REFERENCES approval_workflows(id) ON DELETE CASCADE,
    step_order       INTEGER NOT NULL CHECK (step_order > 0),
    approver_role_id BIGINT  NOT NULL REFERENCES roles(id),
    CONSTRAINT uq_workflow_step_order UNIQUE (workflow_id, step_order)
);

-- =====================================================================
-- 4. REQUISITIONS AND APPROVALS
-- =====================================================================

CREATE TABLE purchase_requisitions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_number VARCHAR(30)  NOT NULL UNIQUE,    -- e.g. PR-2026-0001
    title              VARCHAR(200) NOT NULL,
    justification      TEXT,
    requester_id       BIGINT       NOT NULL REFERENCES users(id),
    department_id      BIGINT       NOT NULL REFERENCES departments(id),
    priority           VARCHAR(10)  NOT NULL DEFAULT 'MEDIUM'
        CHECK (priority IN ('LOW','MEDIUM','HIGH','URGENT')),
    status             VARCHAR(20)  NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','PENDING_APPROVAL','RETURNED','APPROVED',
                          'REJECTED','CANCELLED','CONVERTED')),
    total_amount       NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    required_by_date   DATE,
    workflow_id        BIGINT REFERENCES approval_workflows(id),  -- chosen on submit
    current_step       INTEGER NOT NULL DEFAULT 0,
    submitted_at       TIMESTAMPTZ,
    version            BIGINT  NOT NULL DEFAULT 0,      -- optimistic locking
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE requisition_items (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_id        BIGINT        NOT NULL REFERENCES purchase_requisitions(id) ON DELETE CASCADE,
    category_id           BIGINT        NOT NULL REFERENCES categories(id),
    item_name             VARCHAR(200)  NOT NULL,
    description           VARCHAR(500),
    quantity              INTEGER       NOT NULL CHECK (quantity > 0),
    unit                  VARCHAR(20)   NOT NULL DEFAULT 'NOS',
    estimated_unit_price  NUMERIC(15,2) NOT NULL CHECK (estimated_unit_price >= 0)
);

-- One row per workflow step per submission round (history is kept on resubmission)
CREATE TABLE approvals (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requisition_id   BIGINT  NOT NULL REFERENCES purchase_requisitions(id) ON DELETE CASCADE,
    workflow_step_id BIGINT  NOT NULL REFERENCES approval_workflow_steps(id),
    round_number     INTEGER NOT NULL DEFAULT 1,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','APPROVED','REJECTED','RETURNED','CANCELLED')),
    decided_by       BIGINT REFERENCES users(id),       -- NULL until someone decides
    comments         TEXT,
    decided_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_approval_round_step UNIQUE (requisition_id, round_number, workflow_step_id)
);

-- =====================================================================
-- 5. PURCHASE ORDERS
-- =====================================================================

CREATE TABLE purchase_orders (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number              VARCHAR(30)  NOT NULL UNIQUE,   -- e.g. PO-2026-0001
    requisition_id         BIGINT       NOT NULL REFERENCES purchase_requisitions(id),
    supplier_id            BIGINT       NOT NULL REFERENCES suppliers(id),
    status                 VARCHAR(20)  NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED','ISSUED','CONFIRMED','PARTIALLY_RECEIVED',
                          'RECEIVED','CLOSED','CANCELLED')),
    order_date             DATE         NOT NULL DEFAULT CURRENT_DATE,
    expected_delivery_date DATE,
    total_amount           NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    payment_terms          VARCHAR(100),
    delivery_address       TEXT,
    created_by             BIGINT       NOT NULL REFERENCES users(id),
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE po_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id   BIGINT        NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    requisition_item_id BIGINT        NOT NULL REFERENCES requisition_items(id),
    ordered_quantity    INTEGER       NOT NULL CHECK (ordered_quantity > 0),
    unit_price          NUMERIC(15,2) NOT NULL CHECK (unit_price >= 0),
    received_quantity   INTEGER       NOT NULL DEFAULT 0,
    CONSTRAINT chk_received_within_ordered
        CHECK (received_quantity >= 0 AND received_quantity <= ordered_quantity)
);

-- =====================================================================
-- 6. AUDIT (insert only: rows are never updated or deleted by the app)
-- =====================================================================

CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type  VARCHAR(50) NOT NULL,                  -- e.g. REQUISITION, PURCHASE_ORDER
    entity_id    BIGINT      NOT NULL,
    action       VARCHAR(50) NOT NULL,                  -- e.g. CREATED, SUBMITTED, APPROVED
    performed_by BIGINT      REFERENCES users(id),      -- NULL for system events
    details      TEXT,                                  -- JSON text: old/new values, comments
    ip_address   VARCHAR(45),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- =====================================================================
-- INDEXES on columns used in joins and filters
-- (primary keys and UNIQUE columns are indexed automatically)
